import { execSync } from 'child_process';
import { GeneratedApp, Decision } from '../models/types';

export interface PublishResult {
  repositoryUrl: string;
  branchName: string;
  pullRequestUrl: string;
}

export class GitHubPublisher {
  publish(app: GeneratedApp, decisions: Decision[]): PublishResult {
    const branch = `ddd/${app.projectId}`;

    try {
      execSync(`git checkout -b ${branch}`, { stdio: 'pipe' });

      // Write spec and decisions JSON
      const fs = require('fs') as typeof import('fs');
      fs.writeFileSync('ddd-spec.json', JSON.stringify(app.spec, null, 2));
      fs.writeFileSync('ddd-decisions.json', JSON.stringify(decisions, null, 2));

      execSync('git add ddd-spec.json ddd-decisions.json', { stdio: 'pipe' });
      execSync('git commit -m "chore: DDD generated app"', { stdio: 'pipe' });
      execSync(`git push -u origin ${branch}`, { stdio: 'pipe' });

      const prUrl = execSync(
        `gh pr create --title "DDD: ${app.spec['name'] ?? app.projectId}" --body "Generated by Dopamine Driven Development" --head ${branch}`,
        { stdio: 'pipe' }
      ).toString().trim();

      return {
        repositoryUrl: this._repoUrl(),
        branchName: branch,
        pullRequestUrl: prUrl,
      };
    } catch (err) {
      // GitHub step failed — return partial result so local state is preserved
      return { repositoryUrl: '', branchName: branch, pullRequestUrl: '' };
    }
  }

  private _repoUrl(): string {
    try {
      return execSync('gh repo view --json url -q .url', { stdio: 'pipe' })
        .toString()
        .trim();
    } catch {
      return '';
    }
  }
}
