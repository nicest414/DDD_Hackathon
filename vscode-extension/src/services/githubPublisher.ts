  private _readme(app: GeneratedApp): string {
    return `# ${this._specString(app.spec, 'name', 'DDD Generated App')}

${this._specString(app.spec, 'summary', 'Generated from ddd-spec.json.')}

## Run

Use the package manager available in your environment.

\`\`\`sh
npm install
npm run dev
\`\`\`

\`\`\`sh
pnpm install
pnpm dev
\`\`\`

\`\`\`sh
yarn install
yarn dev
\`\`\`

\`\`\`sh
bun install
bun run dev
\`\`\`
`;
  }

  private _specString(spec: Record<string, unknown>, key: string, fallback: string): string {
    const value = spec[key];
    return typeof value === 'string' && value.trim() ? value.trim() : fallback;
  }

  private _packageName(value: string): string {
    const name = value.toLowerCase().replace(/[^a-z0-9-]+/g, '-').replace(/^-+|-+$/g, '');
    return name || 'ddd-generated-app';
  }

  private _escapeHtml(value: string): string {
    return value
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;')
      .replace(/'/g, '&#39;');
  }
